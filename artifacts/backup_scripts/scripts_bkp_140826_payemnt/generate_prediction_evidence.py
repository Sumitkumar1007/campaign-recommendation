def _filter_training_history_window(training_df: pd.DataFrame, prediction_month_str: str, window_months: int = 3) -> pd.DataFrame:
    if training_df.empty:
        return training_df
    pred_date = pd.to_datetime(prediction_month_str, format="%b-%Y", errors="coerce")
    if pd.isna(pred_date):
        raise ValueError(f"Invalid prediction month format: {prediction_month_str!r}")
    pred_period = pd.Period(pred_date, freq="M")
    
    comm_periods = pd.to_datetime(training_df["MONTH"], format="%b-%Y", errors="coerce").dt.to_period("M")
    start_period = pred_period - window_months
    end_period = pred_period - 1
    mask = (comm_periods >= start_period) & (comm_periods <= end_period)
    return training_df[mask].copy()

def _prepare_probability_map(
    *,
    prediction_rows: pd.DataFrame,
    feature_file: Path,
    schedule_file: Path,
    model_file: Path,
    base_population_file: Path,
    prediction_source_month: str,
) -> dict[tuple[str, str], list[tuple[str, float]]]:
    dataset = prepare_next_month_dataset(
        feature_file=feature_file,
        schedule_file=schedule_file,
        target_offset_months=1,
        history_window_months=int(joblib.load(model_file).get("history_window_months", 1)),
    )
    selected_loans = set(prediction_rows["Loan_number"].astype(str).str.strip())
    base_population = load_base_population(base_population_file, prediction_source_month)
    if selected_loans:
        base_population = base_population[
            base_population["APAC_CARD_NUMBER"].astype(str).str.strip().isin(selected_loans)
        ].copy()
    prediction_population, _blank_population = build_prediction_population(
        dataset=dataset,
        base_population=base_population,
        prediction_source_month=prediction_source_month,
    )
    bundle = joblib.load(model_file)
    ranked_probability_map: dict[tuple[str, str], list[tuple[str, float]]] = {}
    if prediction_population.empty:
        return ranked_probability_map
    X_pred = build_feature_matrix(prediction_population).reindex(columns=bundle["feature_columns"], fill_value=0)
    for day in DAY_COLUMNS:
        if day not in bundle.get("models", {}) or day not in bundle.get("label_encoders", {}):
            continue
        encoder = bundle["label_encoders"][day]
        model = bundle["models"][day]
        _day_predictions, ranked_probabilities = _top_k_labels_with_probabilities(
            model,
            encoder,
            X_pred,
            prediction_population["RISK"],
            evidence_top_n=3,
        )
        for loan_number, probability_rank in zip(prediction_population["APAC_CARD_NUMBER"], ranked_probabilities, strict=False):
            ranked_probability_map[(str(loan_number).strip(), day)] = probability_rank
    return ranked_probability_map


def _readable_strategy(strategy: str) -> str:
    if not strategy or strategy == "-":
        return "no campaign"
    parts = str(strategy).split("-", 2)
    if len(parts) != 3:
        return strategy
    channel, hour, language = parts
    channel_name = {"SMS": "SMS", "WH": "WhatsApp", "VOICE": "voice call", "VOICE_BOT": "voice bot"}.get(channel, channel)
    language_name = "Regional language" if language.upper() == "REGIONAL" else language.title()
    return f"{channel_name} at {hour} in {language_name}"


def _top_historical_success_percentages(counts: dict[str, float]) -> list[tuple[str, float]]:
    ranked_features: list[tuple[str, float, float]] = []
    total_communication = float(counts.get("TOTAL_COMMUNICATION", 0.0) or 0.0)
    
    for column, raw_success_count in counts.items():
        if "_SUCCESS_" not in column:
            continue
        success_count = float(raw_success_count or 0.0)
        # Updated success percentage formula using TOTAL_COMMUNICATION
        success_percentage = round((success_count / total_communication) * 100.0, 2) if total_communication > 0 and success_count > 0 else 0.0
        ranked_features.append((column, success_percentage, success_count))

    ranked_features.sort(key=lambda item: (item[1], item[2], item[0]), reverse=True)
    top_features = [(feature, percentage) for feature, percentage, _success_count in ranked_features[:3]]
    while len(top_features) < 3:
        top_features.append(("", 0.0))
    return top_features


def _prediction_reason(probability: float) -> str:
    return f"Highest probability score in CatBoost model ({probability:.6f})."


def _business_narrative(strategy: str) -> str:
    if strategy == "-":
        return "No outreach strategy was prioritized because historical engagement signals were weak."
    parts = strategy.split("-", 2)
    if len(parts) != 3:
        return f"Strategy selected based on highest model probability for {strategy}."
    channel, hour, language = parts
    channel_name = {"SMS": "SMS", "WH": "WhatsApp", "VOICE": "Voice", "VOICE_BOT": "Voice Bot"}.get(channel, channel)
    return f"Strategy selected due to historical engagement at {hour} via {channel_name} in {language.title()}."


def _fallback_reason(recommended: str, backup: str) -> str:
    if recommended == "-":
        return "No strong outreach signal available."
    if backup:
        return f"If {recommended} underperforms, {backup} is the next best fallback."
    return "No secondary fallback strategy available."


def build_prediction_evidence(
    *,
    prediction_rows: pd.DataFrame,
    training_df: pd.DataFrame,
    ranked_probability_map: dict[tuple[str, str], list[tuple[str, float]]],
    limit: int = 0,
) -> pd.DataFrame:
    exclude_cols = {"APAC_CARD_NUMBER", "MONTH", "DAY", "RISK", "VERTICAL", "PREDICTED_STRATEGY"}
    numeric_feature_cols = [c for c in training_df.columns if c not in exclude_cols and pd.api.types.is_numeric_dtype(training_df[c])]
    
    print("Aggregating 3-month training dataset grouped by loan and DAY...")
    fused_training = (
        training_df.groupby(["APAC_CARD_NUMBER", "DAY"], as_index=False)[numeric_feature_cols]
        .sum()
    )
    
    # Calculate TOTAL_COMMUNICATION as the sum of all individual channel intensity columns for that loan and day
    intensity_cols = [c for c in numeric_feature_cols if c.endswith("_TOTAL_INTENSITY")]
    fused_training["TOTAL_COMMUNICATION"] = fused_training[intensity_cols].sum(axis=1) if intensity_cols else 0.0
    
    all_output_cols = numeric_feature_cols + ["TOTAL_COMMUNICATION"]
    
    fused_training["APAC_CARD_NUMBER"] = fused_training["APAC_CARD_NUMBER"].astype(str).str.strip()
    fused_training["DAY"] = fused_training["DAY"].astype(str).str.strip().str.upper()
    fused_indexed = fused_training.set_index(["APAC_CARD_NUMBER", "DAY"])

    records: list[dict[str, object]] = []

    for _, row in prediction_rows.iterrows():
        loan_number = str(row["Loan_number"]).strip()

        for day in DAY_COLUMNS:
            day_key = str(day).strip().upper()
            
            if (loan_number, day_key) in fused_indexed.index:
                counts = fused_indexed.loc[(loan_number, day_key)].to_dict()
            else:
                counts = {col: 0.0 for col in all_output_cols}

            ranked = ranked_probability_map.get((loan_number, day), [])
            recommended_1 = ranked[0][0] if len(ranked) > 0 else "-"
            probability_1 = float(ranked[0][1]) if len(ranked) > 0 else 0.0
            recommended_2 = ranked[1][0] if len(ranked) > 1 else ""
            probability_2 = float(ranked[1][1]) if len(ranked) > 1 else 0.0
            recommended_3 = ranked[2][0] if len(ranked) > 2 else ""
            probability_3 = float(ranked[2][1]) if len(ranked) > 2 else 0.0
            
            historical_success_features = _top_historical_success_percentages(counts)
            historical_feature_1, historical_percentage_1 = historical_success_features[0]
            historical_feature_2, historical_percentage_2 = historical_success_features[1]
            historical_feature_3, historical_percentage_3 = historical_success_features[2]
            
            record = {
                "loanNumber": loan_number,
                "sourceMonthUsed": str(row["SOURCE_MONTH_USED"]),
                "predictionMonth": str(row["MONTH"]),
                "day": day,
                "risk": str(row["SOURCE_RISK"]),
                "vertical": str(row["SOURCE_VERTICAL"]),
                "recommendedStrategy1": recommended_1,
                "recommendedStrategy1_SuccessProbability": round(probability_1, 6),
                "recommendedStrategy2": recommended_2,
                "recommendedStrategy2_SuccessProbability": round(probability_2, 6),
                "recommendedStrategy3": recommended_3,
                "recommendedStrategy3_SuccessProbability": round(probability_3, 6),
                "recommendedActionText": _readable_strategy(recommended_1),
            }
            record.update(counts)
            record.update(
                {
                    "historical_successfeature1": historical_feature_1,
                    "historical_successprecentage1": historical_percentage_1,
                    "historical_successfeature2": historical_feature_2,
                    "historical_successprecentage2": historical_percentage_2,
                    "historical_successfeature3": historical_feature_3,
                    "historical_successprecentage3": historical_percentage_3,
                    "predictionReason": _prediction_reason(probability_1),
                    "businessNarrative": _business_narrative(recommended_1),
                    "fallbackReason": _fallback_reason(recommended_1, recommended_2),
                }
            )
            records.append(record)

    ordered_columns = [
        "loanNumber",
        "sourceMonthUsed",
        "predictionMonth",
        "day",
        "risk",
        "vertical",
        "recommendedStrategy1",
        "recommendedStrategy1_SuccessProbability",
        "recommendedStrategy2",
        "recommendedStrategy2_SuccessProbability",
        "recommendedStrategy3",
        "recommendedStrategy3_SuccessProbability",
        *all_output_cols,
        "recommendedActionText",
        "historical_successfeature1",
        "historical_successprecentage1",
        "historical_successfeature2",
        "historical_successprecentage2",
        "historical_successfeature3",
        "historical_successprecentage3",
        "predictionReason",
        "businessNarrative",
        "fallbackReason",
    ]
    return pd.DataFrame(records).reindex(columns=ordered_columns)


def print_pit_validation(evidence_df: pd.DataFrame, training_df: pd.DataFrame, sample_loan_number: str) -> None:
    sample_rows = evidence_df[evidence_df["loanNumber"] == sample_loan_number]
    if sample_rows.empty:
        print(f"PIT validation | loanNumber={sample_loan_number} status=no_rows_found")
        return
    loan_train = training_df[training_df["APAC_CARD_NUMBER"].astype(str).str.strip() == sample_loan_number]
    source_month_counts = loan_train.groupby("MONTH", sort=True).size().to_dict() if not loan_train.empty else {}
    print(f"PIT Validation for Loan [{sample_loan_number}] | Total 3-month training rows matched: {len(loan_train):,} | Source month breakdown: {source_month_counts}")


def main() -> None:
    args = parse_args()
    prediction_file = Path(args.prediction_file)
    predictions = _load_prediction_rows(prediction_file)
    if predictions.empty:
        raise ValueError("Prediction file is empty.")
    if args.limit > 0:
        predictions = predictions.head(args.limit).copy()

    prediction_month = str(predictions["MONTH"].iloc[0])
    source_month = str(predictions["SOURCE_MONTH_USED"].iloc[0])
    base_population_file = Path(args.base_population_file) if args.base_population_file else _default_cases_file(prediction_month)
    output_file = ensure_parent_dir(Path(args.output_file) if args.output_file else prediction_evidence_file(prediction_file))

    training_file = Path(args.training_dataset_file)
    if not training_file.exists():
        fallback_path = TRAINING_DATA_DIR / "strategy_training_dataset_inference.csv"
        if fallback_path.exists():
            print(f"[WARNING] Training dataset not found at {training_file}. Falling back to inference dataset: {fallback_path}")
            training_file = fallback_path
        else:
            raise FileNotFoundError(f"Training dataset not found at {training_file} and fallback {fallback_path} is also missing.")
    
    print(f"Loading training dataset from {training_file} ...")
    training_df = pd.read_csv(training_file)
    training_df["APAC_CARD_NUMBER"] = training_df["APAC_CARD_NUMBER"].fillna("").astype(str).str.strip()
    training_df["MONTH"] = training_df["MONTH"].fillna("").astype(str).str.strip().str.upper()
    training_df["DAY"] = training_df["DAY"].fillna("").astype(str).str.strip().str.upper()

    training_df = _filter_training_history_window(training_df, prediction_month, window_months=3)

    print("\n" + "="*60)
    print("TRAINING DATASET EVIDENCE AUDIT REPORT")
    print("="*60)
    print(f"Loaded training dataset file: {training_file.name}")
    print(f"Total training rows in 3-month rolling window: {len(training_df):,}")
    if not training_df.empty:
        print("\nBreakdown by MONTH column in training dataset:")
        print(training_df["MONTH"].value_counts().to_string())
    print("="*60 + "\n")

    ranked_probability_map = _prepare_probability_map(
        prediction_rows=predictions,
        feature_file=Path(args.feature_file),
        schedule_file=Path(args.schedule_file),
        model_file=Path(args.model_file),
        base_population_file=base_population_file,
        prediction_source_month=source_month,
    )
    
    evidence = build_prediction_evidence(
        prediction_rows=predictions,
        training_df=training_df,
        ranked_probability_map=ranked_probability_map,
        limit=args.limit,
    )
    
    evidence.to_csv(output_file, index=False)
    print(f"Saved {len(evidence):,} evidence rows to {output_file}")

    sample_loan_number = args.sample_loan_number or (str(evidence["loanNumber"].iloc[0]) if not evidence.empty else "")
    if sample_loan_number:
        print_pit_validation(evidence, training_df, sample_loan_number)


if __name__ == "__main__":
    main()