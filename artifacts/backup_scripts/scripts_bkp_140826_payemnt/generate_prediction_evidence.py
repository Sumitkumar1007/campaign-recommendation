def prediction_evidence_file(prediction_file: Path) -> Path:
    parts = prediction_file.stem.split("_")
    if len(parts) >= 2 and parts[0].isdigit() and len(parts[0]) == 4 and parts[1].isdigit() and len(parts[1]) == 2:
        prefix = f"{parts[0]}_{parts[1]}"
    else:
        prefix = prediction_file.stem
    return prediction_file.with_name(f"{prefix}_strategy_predictions_catboost_3m_prediction_evidence.csv")


def _month_token(month_label: str) -> str:
    period = pd.to_datetime(pd.Series([month_label]), format="%b-%Y", errors="coerce").dt.to_period("M").iloc[0]
    if pd.isna(period):
        raise ValueError(f"Invalid month label {month_label!r}.")
    return period.to_timestamp().strftime("%b%Y").upper()


def _default_cases_file(prediction_month: str) -> Path:
    return CASE_DATA_DIR / f"digital_cases_{_month_token(prediction_month)}.csv"


def _load_prediction_rows(prediction_file: Path) -> pd.DataFrame:
    predictions = pd.read_csv(prediction_file).copy()
    required = {"Loan_number", "SOURCE_MONTH_USED", "MONTH", "EMI_DATE", "SOURCE_RISK", "SOURCE_VERTICAL"}
    missing = required.difference(predictions.columns)
    if missing:
        raise ValueError(f"Prediction file is missing required columns: {sorted(missing)}")
    return predictions


