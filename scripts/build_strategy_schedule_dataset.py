from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from pipeline_common import DAY_WEIGHT_COLUMN_MAP, DAY_WEIGHT_COLUMNS, SCHEDULE_DAY_COLUMNS
from project_paths import SCHEDULE_DATA_DIR, TRAINING_DATA_DIR, ensure_parent_dir


DAY_ORDER = SCHEDULE_DAY_COLUMNS


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Convert the month-level strategy rows into a schedule-style dataset "
            "with one row per APAC card and month."
        )
    )
    # parser.add_argument(
    #     "--input-file",
    #     default=str(TRAINING_DATA_DIR / "strategy_training_dataset_all_months.csv"),
    #     help="Month-level strategy dataset generated by generate_strategy_dataset.py",
    # )
    # parser.add_argument(
    #     "--output-file",
    #     default=str(SCHEDULE_DATA_DIR / "strategy_schedule_dataset_all_months.csv"),
    #     help="Path to save the schedule-shaped dataset.",
    # )
    parser.add_argument(
        "--input-file",
        # --- ADD _train ---
        default=str(TRAINING_DATA_DIR / "strategy_training_dataset_train.csv"),
        help="Day-level feature dataset generated by generate_strategy_dataset.py",
    )
    parser.add_argument(
        "--output-file",
        # --- FIXED THIS TO _train.csv ---
        default=str(SCHEDULE_DATA_DIR / "strategy_schedule_dataset_train.csv"),
        help="Path to save the schedule-shaped dataset.",
    )
    return parser.parse_args()


def normalize_risk(series: pd.Series) -> pd.Series:
    return (
        series.fillna("UNKNOWN")
        .astype(str)
        .str.strip()
        .replace({"": "UNKNOWN"})
        .str.upper()
    )


def main() -> None:
    args = parse_args()
    input_file = Path(args.input_file)
    output_file = ensure_parent_dir(args.output_file)

    df = pd.read_csv(input_file)
    if df.empty:
        raise ValueError("Input dataset is empty.")

    required_columns = {"MONTH", "DAY", "PREDICTED_STRATEGY"}
    if "RISK" not in df.columns:
        raise ValueError("Missing required RISK column. Risk must come from communications.")

    key_column = "ENTITY_KEY" if "ENTITY_KEY" in df.columns else "APAC_CARD_NUMBER"
    required_columns.add(key_column)
    missing = required_columns - set(df.columns)
    if missing:
        raise ValueError(f"Missing required columns: {sorted(missing)}")

    df = df.copy()
    df["RISK"] = normalize_risk(df["RISK"])
    df = df[df["RISK"].ne("UNKNOWN")].copy()
    df["PREDICTED_STRATEGY"] = (
        df["PREDICTED_STRATEGY"]
        .fillna("-")
        .astype(str)
        .str.replace(r"^VOICE-", "IVR-", regex=True)
    )

    risk_df = df.groupby([key_column, "MONTH"])["RISK"].last().reset_index()

    wide = (
        df.pivot_table(
            index=[key_column, "MONTH"],
            columns="DAY",
            values="PREDICTED_STRATEGY",
            aggfunc="first",
            fill_value="-",
        )
        .reset_index()
    )

    for day in DAY_ORDER:
        if day not in wide.columns:
            wide[day] = "-"

    wide["D"] = "-"

    if "TARGET_SAMPLE_WEIGHT" in df.columns:
        weight_wide = (
            df.pivot_table(
                index=[key_column, "MONTH"],
                columns="DAY",
                values="TARGET_SAMPLE_WEIGHT",
                aggfunc="max",
                fill_value=1.0,
            )
            .reset_index()
        )
        for day in DAY_WEIGHT_COLUMN_MAP:
            if day not in weight_wide.columns:
                weight_wide[day] = 1.0
        weight_wide = weight_wide[[key_column, "MONTH", *DAY_WEIGHT_COLUMN_MAP.keys()]]
        weight_wide = weight_wide.rename(columns=DAY_WEIGHT_COLUMN_MAP)
    else:
        weight_wide = wide[[key_column, "MONTH"]].copy()
        for column in DAY_WEIGHT_COLUMNS:
            weight_wide[column] = 1.0

    wide = wide.merge(weight_wide, on=[key_column, "MONTH"], how="left")
    wide = wide.merge(risk_df, on=[key_column, "MONTH"], how="left")
    wide = wide.rename(columns={key_column: "ENTITY_KEY"})
    wide = wide[["RISK", "ENTITY_KEY", "MONTH", *DAY_ORDER, *DAY_WEIGHT_COLUMNS]]
    wide = wide.sort_values(["RISK", "ENTITY_KEY", "MONTH"]).reset_index(drop=True)
    wide.to_csv(output_file, index=False)
    print(f"Saved {len(wide):,} rows to {output_file}")


if __name__ == "__main__":
    main()
