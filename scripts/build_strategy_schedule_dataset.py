from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from pipeline_common import (
    DAY_WEIGHT_COLUMN_MAP,
    DAY_WEIGHT_COLUMNS,
    SCHEDULE_DAY_COLUMNS,
    load_default_config,
    offsets_to_day_columns,
    parse_day_offset,
)
from project_paths import SCHEDULE_DATA_DIR, TRAINING_DATA_DIR, ensure_parent_dir


DAY_ORDER = SCHEDULE_DAY_COLUMNS


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Convert the month-level strategy rows into a schedule-style dataset "
            "with one row per APAC card and month."
        )
    )
    parser.add_argument(
        "--input-file",
        default=str(TRAINING_DATA_DIR / "strategy_training_dataset_train.csv"),
        help="Day-level feature dataset generated by generate_strategy_dataset.py",
    )
    parser.add_argument(
        "--output-file",
        default=str(SCHEDULE_DATA_DIR / "strategy_schedule_dataset_train.csv"),
        help="Path to save the schedule-shaped dataset.",
    )
    parser.add_argument(
        "--config-file",
        default="",
        help="Optional path to config JSON file with allowed_day_offsets for dynamic columns.",
    )
    parser.add_argument(
        "--allowed-day-offsets",
        nargs="*",
        default=None,
        help="Allowed day offsets for dynamic columns (e.g. -5 -4 -3 -2 -1 1 2 3 4 5). Overrides config-file.",
    )
    return parser.parse_args()


def normalize_risk(series: pd.Series) -> pd.Series:
    cleaned = series.fillna("UNKNOWN").astype(str).str.strip().str.upper()
    return cleaned.replace({
        "": "UNKNOWN",
        "NAN": "UNKNOWN",
        "NONE": "UNKNOWN",
        "NULL": "UNKNOWN",
        "<NA>": "UNKNOWN",
    })


def main() -> None:
    args = parse_args()
    input_file = Path(args.input_file)
    output_file = ensure_parent_dir(args.output_file)

    df = pd.read_csv(input_file)
    if df.empty:
        raise ValueError("Input dataset is empty.")

    required_columns = {"MONTH", "DAY", "PREDICTED_STRATEGY"}
    if "RISK" not in df.columns:
        raise ValueError("Missing required RISK column. Risk must come from communications.")

    key_column = "ENTITY_KEY" if "ENTITY_KEY" in df.columns else "APAC_CARD_NUMBER"
    required_columns.add(key_column)
    missing = required_columns - set(df.columns)
    if missing:
        raise ValueError(f"Missing required columns: {sorted(missing)}")

    df = df.copy()
    df["RISK"] = normalize_risk(df["RISK"])
    df["PREDICTED_STRATEGY"] = (
        df["PREDICTED_STRATEGY"]
        .fillna("-")
        .astype(str)
        .str.replace(r"^VOICE-", "IVR-", regex=True)
    )

    df_sorted = df.copy()
    df_sorted["_is_known"] = df_sorted["RISK"].ne("UNKNOWN").astype(int)
    risk_df = (
        df_sorted.sort_values([key_column, "MONTH", "_is_known"], ascending=[True, True, False])
        .drop_duplicates(subset=[key_column, "MONTH"], keep="first")
        [[key_column, "MONTH", "RISK"]]
        .reset_index(drop=True)
    )

    wide = (
        df.pivot_table(
            index=[key_column, "MONTH"],
            columns="DAY",
            values="PREDICTED_STRATEGY",
            aggfunc="first",
            fill_value="-",
        )
        .reset_index()
    )

    if args.allowed_day_offsets is not None and len(args.allowed_day_offsets) > 0:
        parsed_offsets = [parse_day_offset(o) for o in args.allowed_day_offsets]
        allowed_offsets = [o for o in parsed_offsets if o is not None and o != 0]
    else:
        app_config = load_default_config(args.config_file) if args.config_file else {}
        allowed_offsets = app_config.get("allowed_day_offsets")
    if allowed_offsets is not None:
        allowed_days = offsets_to_day_columns(allowed_offsets)
        active_day_order = [d for d in DAY_ORDER if d in allowed_days or (d == "D" and 0 in allowed_offsets)]
    else:
        active_day_order = list(DAY_ORDER)

    for day in active_day_order:
        if day not in wide.columns:
            wide[day] = "-"

    if "D" in active_day_order:
        wide["D"] = "-"

    active_weight_cols = [DAY_WEIGHT_COLUMN_MAP[d] for d in active_day_order if d in DAY_WEIGHT_COLUMN_MAP]

    if "TARGET_SAMPLE_WEIGHT" in df.columns:
        weight_wide = (
            df.pivot_table(
                index=[key_column, "MONTH"],
                columns="DAY",
                values="TARGET_SAMPLE_WEIGHT",
                aggfunc="max",
                fill_value=1.0,
            )
            .reset_index()
        )
        for day in active_day_order:
            if day in DAY_WEIGHT_COLUMN_MAP:
                col_name = DAY_WEIGHT_COLUMN_MAP[day]
                if day not in weight_wide.columns:
                    weight_wide[col_name] = 1.0
                else:
                    weight_wide[col_name] = weight_wide[day]
        weight_wide = weight_wide[[key_column, "MONTH", *active_weight_cols]]
    else:
        weight_wide = wide[[key_column, "MONTH"]].copy()
        for column in active_weight_cols:
            weight_wide[column] = 1.0

    wide[key_column] = wide[key_column].astype(str).str.strip()
    weight_wide[key_column] = weight_wide[key_column].astype(str).str.strip()
    risk_df[key_column] = risk_df[key_column].astype(str).str.strip()
    wide = wide.merge(weight_wide, on=[key_column, "MONTH"], how="left")
    wide = wide.merge(risk_df, on=[key_column, "MONTH"], how="left")
    wide = wide.rename(columns={key_column: "ENTITY_KEY"})
    wide = wide[["RISK", "ENTITY_KEY", "MONTH", *active_day_order, *active_weight_cols]]
    wide = wide.sort_values(["RISK", "ENTITY_KEY", "MONTH"]).reset_index(drop=True)
    wide.to_csv(output_file, index=False)
    print(f"Saved {len(wide):,} rows to {output_file}")


if __name__ == "__main__":
    main()
