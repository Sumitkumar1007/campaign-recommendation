from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from project_paths import SCHEDULE_DATA_DIR, TRAINING_DATA_DIR, ensure_parent_dir


DAY_ORDER = ["D-5", "D-4", "D-3", "D-2", "D-1", "D", "D+1", "D+2", "D+3", "D+4", "D+5"]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Convert the month-level strategy rows into a schedule-style dataset "
            "with one row per APAC card and month."
        )
    )
    parser.add_argument(
        "--input-file",
        default=str(TRAINING_DATA_DIR / "strategy_training_dataset_sample_10_v5.csv"),
        help="Month-level strategy dataset generated by generate_strategy_dataset.py",
    )
    parser.add_argument(
        "--output-file",
        default=str(SCHEDULE_DATA_DIR / "strategy_schedule_dataset.csv"),
        help="Path to save the schedule-shaped dataset.",
    )
    return parser.parse_args()


def derive_risk(row: pd.Series) -> str:
    voice_intensity = float(row.get("VOICE_TOTAL_INTENSITY", 0) or 0)
    sms_intensity = float(row.get("SMS_TOTAL_INTENSITY", 0) or 0)
    wh_intensity = float(row.get("WH_TOTAL_INTENSITY", 0) or 0)

    voice_failures = sum(
        float(row[col] or 0)
        for col in row.index
        if col.startswith("VOICE_FAILED_")
    )
    digital_success = sum(
        float(row[col] or 0)
        for col in row.index
        if (
            col.startswith("SMS_SUCCESS_")
            or col.startswith("WH_SUCCESS_")
        )
    )

    total_intensity = sms_intensity + wh_intensity + voice_intensity
    if total_intensity == 0:
        return "LOW"

    voice_failure_ratio = voice_failures / voice_intensity if voice_intensity else 0.0
    digital_success_ratio = digital_success / total_intensity

    if voice_failure_ratio >= 0.7 and digital_success_ratio < 0.35:
        return "HIGH"
    if digital_success_ratio >= 0.55:
        return "LOW"
    return "MEDIUM"


def main() -> None:
    args = parse_args()
    input_file = Path(args.input_file)
    output_file = ensure_parent_dir(args.output_file)

    df = pd.read_csv(input_file)
    if df.empty:
        raise ValueError("Input dataset is empty.")

    required_columns = {"APAC_CARD_NUMBER", "MONTH", "DAY", "PREDICTED_STRATEGY"}
    missing = required_columns - set(df.columns)
    if missing:
        raise ValueError(f"Missing required columns: {sorted(missing)}")

    df = df.copy()
    df["PREDICTED_STRATEGY"] = (
        df["PREDICTED_STRATEGY"]
        .fillna("-")
        .astype(str)
        .replace({"VOICE": "IVR"}, regex=True)
    )

    risk_df = (
        df.groupby(["APAC_CARD_NUMBER", "MONTH"], as_index=False)
        .apply(lambda g: pd.Series({"RISK": derive_risk(g.sum(numeric_only=True))}))
        .reset_index(drop=True)
    )

    wide = (
        df.pivot_table(
            index=["APAC_CARD_NUMBER", "MONTH"],
            columns="DAY",
            values="PREDICTED_STRATEGY",
            aggfunc="first",
            fill_value="-",
        )
        .reset_index()
    )

    for day in DAY_ORDER:
        if day not in wide.columns:
            wide[day] = "-"

    wide["D"] = "-"
    wide = wide.merge(risk_df, on=["APAC_CARD_NUMBER", "MONTH"], how="left")
    wide = wide.rename(columns={"APAC_CARD_NUMBER": "Loan_number"})
    wide = wide[["RISK", "Loan_number", "MONTH", *DAY_ORDER]]
    wide = wide.sort_values(["RISK", "Loan_number", "MONTH"]).reset_index(drop=True)
    wide.to_csv(output_file, index=False)
    print(f"Saved {len(wide):,} rows to {output_file}")


if __name__ == "__main__":
    main()
