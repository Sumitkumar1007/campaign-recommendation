from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from entity_keys import normalize_identifier
from project_paths import FEATURE_DATA_DIR, TRAINING_DATA_DIR, ensure_parent_dir

from append_payment_flags import load_paid_keys

PAYMENT_COUNT_COLUMNS = {"LINK_PAYMENT_COUNT", "EXT_PAYMENT_COUNT", "TOTAL_PAYMENT_COUNT"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build a low-memory monthly feature table from the day-level strategy dataset."
    )
    parser.add_argument(
        "--input-file",
        default=str(TRAINING_DATA_DIR / "strategy_training_dataset_train.csv"),
        help="Day-level feature dataset generated by generate_strategy_dataset.py",
    )
    parser.add_argument(
        "--output-file",
        default=str(FEATURE_DATA_DIR / "strategy_monthly_features_train.csv"),
        help="Output CSV for monthly aggregated features.",
    )
    parser.add_argument(
        "--payment-files",
        nargs="*",
        default=[],
        help="Optional payment CSV files or consolidated payment report to incorporate payment count features.",
    )
    parser.add_argument(
        "--chunksize",
        type=int,
        default=200_000,
        help="Chunk size for reading the large day-level CSV.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    input_file = Path(args.input_file)
    output_file = ensure_parent_dir(args.output_file)

    monthly_parts: list[pd.DataFrame] = []
    risk_parts: list[pd.Series] = []
    vertical_parts: list[pd.Series] = []
    key_column: str | None = None
    for chunk in pd.read_csv(input_file, chunksize=args.chunksize):
        active_key = "ENTITY_KEY" if "ENTITY_KEY" in chunk.columns else "APAC_CARD_NUMBER"
        if key_column is None:
            key_column = active_key
        numeric_columns = [
            col
            for col in chunk.columns
            if col not in {active_key, "MONTH", "DAY", "RISK", "VERTICAL", "PREDICTED_STRATEGY", "TARGET_SAMPLE_WEIGHT"}
        ]
        if "RISK" not in chunk.columns:
            raise ValueError("Missing required RISK column. Risk must come from communications.")

        agg_spec = {col: ("max" if col in PAYMENT_COUNT_COLUMNS else "sum") for col in numeric_columns}
        grouped = (
            chunk[[active_key, "MONTH", *numeric_columns]]
            .groupby([key_column, "MONTH"], as_index=False)
            .agg(agg_spec)
        )
        monthly_parts.append(grouped)
        risk_parts.append(chunk.groupby([active_key, "MONTH"])["RISK"].first())
        if "VERTICAL" in chunk.columns:
            vertical_parts.append(chunk.groupby([active_key, "MONTH"])["VERTICAL"].first())

    if not monthly_parts:
        raise ValueError("No data found while building monthly features.")

    sample_num_cols = [c for c in monthly_parts[0].columns if c not in {key_column, "MONTH"}]
    agg_spec_final = {col: ("max" if col in PAYMENT_COUNT_COLUMNS else "sum") for col in sample_num_cols}
    monthly = (
        pd.concat(monthly_parts, ignore_index=True)
        .groupby([key_column, "MONTH"], as_index=False)
        .agg(agg_spec_final)
    )

    # Ensure payment count columns always exist
    for pay_col in ["LINK_PAYMENT_COUNT", "EXT_PAYMENT_COUNT", "TOTAL_PAYMENT_COUNT"]:
        if pay_col not in monthly.columns:
            monthly[pay_col] = 0.0
        else:
            monthly[pay_col] = monthly[pay_col].fillna(0.0)

    # If payment files/reports provided, map payment counts per (key, month)
    payment_files = [Path(p) for p in args.payment_files]
    if payment_files:
        print("Incorporating payment report counts into monthly features...")
        _, _, _, _, link_pay_counts, ext_pay_counts, tot_pay_counts = load_paid_keys(payment_files)
        for idx, row in monthly.iterrows():
            entity = str(row[key_column]).strip()
            month = str(row["MONTH"]).strip().upper()
            k = (entity, month)
            l_c = link_pay_counts.get(k, 0)
            e_c = ext_pay_counts.get(k, 0)
            t_c = tot_pay_counts.get(k, 0)
            if l_c > 0:
                monthly.at[idx, "LINK_PAYMENT_COUNT"] = max(float(monthly.at[idx, "LINK_PAYMENT_COUNT"]), float(l_c))
            if e_c > 0:
                monthly.at[idx, "EXT_PAYMENT_COUNT"] = max(float(monthly.at[idx, "EXT_PAYMENT_COUNT"]), float(e_c))
            if t_c > 0:
                monthly.at[idx, "TOTAL_PAYMENT_COUNT"] = max(float(monthly.at[idx, "TOTAL_PAYMENT_COUNT"]), float(t_c))

    risk_df = (
        pd.concat(risk_parts, ignore_index=False)
        .groupby(level=[0, 1])
        .first()
        .reset_index()
    )
    monthly[key_column] = normalize_identifier(monthly[key_column])
    risk_df[key_column] = normalize_identifier(risk_df[key_column])
    monthly = monthly.merge(risk_df, on=[key_column, "MONTH"], how="left")
    if vertical_parts:
        vertical_df = (
            pd.concat(vertical_parts, ignore_index=False)
            .groupby(level=[0, 1])
            .first()
            .reset_index()
        )
        vertical_df[key_column] = normalize_identifier(vertical_df[key_column])
        monthly = monthly.merge(vertical_df, on=[key_column, "MONTH"], how="left")
    monthly.to_csv(output_file, index=False)
    print(f"Saved {len(monthly):,} rows to {output_file}")


if __name__ == "__main__":
    main()
